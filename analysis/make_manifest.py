"""Write MANIFEST.md: for every table and figure of the manuscript, the command
that produces it, its input files and SHA-256 checksums of every input and
output, so a reader can confirm that a checkout matches the published paper.

    python3 analysis/make_manifest.py
"""
import hashlib, os, platform, subprocess, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
ITEMS = [
    ("Table 3 (closed set), Tables 4-6, Figs. 2-3", "python3 analysis/openset_eval.py && python3 analysis/make_tables.py && python3 analysis/make_figures.py",
     ["results/dataset3.csv.gz"], ["results/openset_results.json"]),
    ("Tables 7-8 (fold-level, PR-AUC, onboard-only, bootstrap)", "python3 analysis/extra_metrics.py && python3 analysis/make_tables.py",
     ["results/dataset3.csv.gz"], ["results/extra_metrics.json"]),
    ("Table 9 (operating points), Table 10 (frozen detectors under stress), Table 11 (independent campaign)",
     "python3 analysis/fixed_detector_eval.py --indep runs_indep --stress-fix runs_nu_fix --stress-honest runs_nu && python3 analysis/make_fixed_tables.py",
     ["results/dataset3.csv.gz", "results/independent_runs.csv.gz"], ["results/fixed_detector.json"]),
    ("Table 12 (open-set baselines and fusion ablation)", "python3 analysis/openset_baselines.py",
     ["results/dataset3.csv.gz"], ["results/openset_baselines.json"]),
    ("Fig. 4 and stress-test text (nu alone)", "python3 analysis/nu_robustness_report.py --fixed runs_nu_fix --honest runs_nu && python3 analysis/make_figures.py",
     [], ["results/nu_robustness.csv"]),
    ("Table 13 (computational cost)", "python3 analysis/complexity.py && python3 analysis/make_tables.py",
     ["results/dataset3.csv.gz"], ["results/complexity.json"]),
]


def sha(p):
    p = os.path.join(ROOT, p)
    if not os.path.exists(p):
        return "missing"
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def main():
    try:
        commit = subprocess.check_output(["git", "-C", ROOT, "rev-parse", "HEAD"], text=True).strip()
    except Exception:
        commit = "unknown"
    L = ["# Execution manifest", "",
         "Generated by `analysis/make_manifest.py`. The checksums identify the exact data and",
         "result files behind every table and figure of the manuscript.", "",
         f"Manifest written at parent commit `{commit}` (the commit that adds this file is its child).",
         f"Python {platform.python_version()}.", "",
         "| Paper item | Command | Inputs | Outputs |", "|---|---|---|---|"]
    for item, cmd, ins, outs in ITEMS:
        L.append(f"| {item} | `{cmd}` | {', '.join(f'`{i}`' for i in ins) or 'stress runs (regenerated by `analysis/nu_robustness.py`)'} | "
                 f"{', '.join(f'`{o}`' for o in outs)} |")
    L += ["", "## Checksums (SHA-256)", "", "```"]
    files = sorted({f for _, _, i, o in ITEMS for f in i + o} |
                   {os.path.join("results/tables", t) for t in sorted(os.listdir(os.path.join(ROOT, "results/tables")))})
    for f in files:
        L.append(f"{sha(f)}  {f}")
    L += ["```", ""]
    open(os.path.join(ROOT, "MANIFEST.md"), "w").write("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
